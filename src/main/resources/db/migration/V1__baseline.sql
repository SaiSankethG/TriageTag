-- V1: the schema as it was on 4 Nov 2026, when Hibernate (ddl-auto: update) still created it.
-- Taken from `pg_dump --schema-only` of the running DB, with one change: no CHECK (source = 'GITHUB'),
-- so other sources (Jira) can be stored later. Names (sequence, foreign key) are Hibernate's, kept as-is
-- so this file describes the existing database exactly.
--
-- The existing database is NOT built by this file: Flyway "baselines" it at version 1 (it already
-- has these tables). This file builds the schema on an EMPTY database, e.g. in tests.

CREATE TABLE issue (
    id                 bigint                      NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME issue_id_seq),
    author_association character varying(30)       NOT NULL,
    body               text,
    closed_at          timestamp(6) with time zone,
    created_at         timestamp(6) with time zone NOT NULL,
    duplicate_of       integer,
    external_id        character varying(64)       NOT NULL,
    html_url           text                        NOT NULL,
    issue_type         character varying(50),
    milestone          character varying(100),
    number             integer                     NOT NULL,
    raw                jsonb                       NOT NULL,
    repo               character varying(200)      NOT NULL,
    source             character varying(20)       NOT NULL,
    state              character varying(20)       NOT NULL,
    state_reason       character varying(30),
    title              text                        NOT NULL,
    updated_at         timestamp(6) with time zone NOT NULL,
    CONSTRAINT issue_pkey PRIMARY KEY (id),
    CONSTRAINT uq_issue_source_external UNIQUE (source, external_id)   -- re-runs update, never duplicate
);

CREATE INDEX idx_issue_repo_created ON issue USING btree (repo, created_at);   -- replay in date order per repo

CREATE TABLE issue_label (
    issue_id   bigint                 NOT NULL,
    label_name character varying(100) NOT NULL,
    CONSTRAINT issue_label_pkey PRIMARY KEY (issue_id, label_name),
    CONSTRAINT fkit5n9c0frugu5m8xqsxtps63r FOREIGN KEY (issue_id) REFERENCES issue (id) ON DELETE CASCADE
);

CREATE INDEX idx_issue_label_name ON issue_label USING btree (label_name);    -- "all issues labelled X"
