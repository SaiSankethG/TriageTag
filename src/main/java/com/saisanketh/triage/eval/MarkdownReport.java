package com.saisanketh.triage.eval;

import com.saisanketh.triage.eval.EvalReport.FalseAlarms;
import com.saisanketh.triage.eval.EvalReport.LabelScore;
import com.saisanketh.triage.eval.EvalReport.SearchScore;

import java.util.Locale;
import java.util.stream.Collectors;

/** Turns an EvalReport into the markdown of docs/m3-results.md. */
final class MarkdownReport {

    private MarkdownReport() {
    }

    static String render(EvalReport r) {
        var a = r.answerKey();
        return """
                # M3 results: duplicate search replay on %s

                Generated by `POST /eval/%s` (EvalService). Duration: %.1f s.

                ## Scored set
                | | Count |
                |---|---|
                | Issues with `duplicate_of` (answer key) | %d |
                | Excluded: original is not a stored issue (most likely a pull request) | %d |
                | Excluded: "original" is not older than the duplicate (a time-ordered search can't find it) | %d |
                | **Scored pairs** | **%d** |

                Each duplicate is searched as if it had just been opened: only earlier issues of the same repo.

                ## Duplicate search: keyword vs vector
                Candidate filter: %s

                | Method | recall@1 | recall@3 | recall@10 | MRR (top 10) |
                |---|---|---|---|---|
                %s
                %s
                %s
                %s

                "with filter" is what the app does: earlier issues with an excluded label (bookkeeping copies) are never
                candidates. "no filter" searches every earlier issue (the M3 numbers). False alarms and labels below use
                the filter.

                ## False alarms (vector, top-1 score)
                Random non-duplicate issues (no `duplicate_of`, not closed as duplicate, no duplicate label). The threshold is
                the lowest cosine similarity at which at most 10%% of them would be flagged "likely duplicate".

                | Population | Sample | Threshold | False-alarm rate | Duplicates flagged | Original is top-1 (and flagged) | Original in top 3 (and flagged) |
                |---|---|---|---|---|---|---|
                %s
                %s

                "External reporters" = issues opened by someone who is not OWNER/MEMBER/COLLABORATOR: what a triage assistant
                actually sees. "All issues" also contains the team's bookkeeping issues (forward-port clones, "Upgrade to X"),
                which have near-identical earlier twins and push the threshold up.

                ## Label suggestion (top suggested label vs the real labels)
                | Population | Issues (most recent, with a real label) | With a suggestion (coverage) | Top label correct (precision) |
                |---|---|---|---|
                %s
                %s

                Workflow labels (`status:`) are ignored on both sides.
                """.formatted(
                r.repo(), r.repo(), r.durationMs() / 1000.0,
                a.withDuplicateOf(), a.originalNotStored(), a.originalNewer(), a.scored(),
                filterText(r),
                row(r.keyword(), "with filter"), row(r.vector(), "with filter"),
                row(r.keywordUnfiltered(), "no filter"), row(r.vectorUnfiltered(), "no filter"),
                row("External reporters", r.falseAlarms(), a.scored()),
                row("All issues", r.falseAlarmsAllIssues(), a.scored()),
                row("External reporters", r.labels()),
                row("All issues", r.labelsAllIssues()));
    }

    private static String filterText(EvalReport r) {
        return r.excludedLabels().isEmpty()
                ? "none configured for this repo."
                : "issues labelled " + r.excludedLabels().stream().map(l -> "`" + l + "`").collect(Collectors.joining(", "))
                        + " are not candidates (`triage.candidates.exclude-labels`).";
    }

    private static String row(SearchScore s, String filter) {
        return String.format(Locale.ROOT, "| %s, %s | %s (%d) | %s (%d) | %s (%d) | %.3f |", s.method(), filter,
                pct(s.recallAt1()), s.hitsAt1(), pct(s.recallAt3()), s.hitsAt3(), pct(s.recallAt10()), s.hitsAt10(),
                s.mrr());
    }

    private static String row(String population, FalseAlarms f, int scored) {
        return String.format(Locale.ROOT, "| %s | %d | %.3f | %s | %d of %d | %s | %s |", population, f.sample(),
                f.threshold(), pct(f.falseAlarmRate()), f.duplicatesFlagged(), scored,
                pct(f.recallAtThresholdTop1()), pct(f.recallAtThresholdTop3()));
    }

    private static String row(String population, LabelScore l) {
        return String.format(Locale.ROOT, "| %s | %d | %d (%s) | %d (%s) |", population, l.issues(),
                l.withSuggestion(), pct(l.coverage()), l.topCorrect(), pct(l.precision()));
    }

    private static String pct(double share) {
        return String.format(Locale.ROOT, "%.1f%%", share * 100);
    }
}
