package com.saisanketh.triage.domain;

import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.annotations.OnDelete;
import org.hibernate.annotations.OnDeleteAction;
import org.hibernate.type.SqlTypes;

import java.time.Instant;
import java.util.HashSet;
import java.util.Set;

/**
 * One issue from an issue tracker (GitHub for now). Maps to the "issue" table in docs/schema.md.
 */
@Entity
@Table(
        name = "issue",
        uniqueConstraints = @UniqueConstraint(
                name = "uq_issue_source_external",
                columnNames = {"source", "external_id"}),
        indexes = @Index(name = "idx_issue_repo_created", columnList = "repo, created_at"))
@Getter
@Setter
@NoArgsConstructor
public class Issue {

    /** Our own id, generated by Postgres (bigserial). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** Stored as the enum name, e.g. 'GITHUB'. */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private SourceType source;

    /** The tracker's own id, as text so Jira keys like 'KAFKA-123' also fit. */
    @Column(name = "external_id", nullable = false, length = 64)
    private String externalId;

    /** e.g. 'spring-projects/spring-boot'. */
    @Column(nullable = false, length = 200)
    private String repo;

    /** Issue number shown on GitHub, e.g. 52529. */
    @Column(nullable = false)
    private Integer number;

    @Column(nullable = false, columnDefinition = "text")
    private String title;

    /** Can be null: GitHub allows an empty body. */
    @Column(columnDefinition = "text")
    private String body;

    /** 'open' or 'closed'. */
    @Column(nullable = false, length = 20)
    private String state;

    /** completed / not_planned / duplicate / reopened; null while open and on old closed issues. */
    @Column(name = "state_reason", length = 30)
    private String stateReason;

    /** Bug / Feature; null when the repo doesn't use issue types. */
    @Column(name = "issue_type", length = 50)
    private String issueType;

    /** OWNER / MEMBER / CONTRIBUTOR / NONE ... */
    @Column(name = "author_association", nullable = false, length = 30)
    private String authorAssociation;

    /** Milestone title, e.g. '3.4.2'. */
    @Column(length = 100)
    private String milestone;

    @Column(name = "html_url", nullable = false, columnDefinition = "text")
    private String htmlUrl;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    /** Null while open. */
    @Column(name = "closed_at")
    private Instant closedAt;

    /** Answer key: number of the original issue in the same repo; null unless closed as a duplicate. */
    @Column(name = "duplicate_of")
    private Integer duplicateOf;

    /** The full JSON the tracker sent, stored as jsonb so we can re-process without re-downloading. */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(nullable = false)
    private String raw;

    /** Label names, stored in their own table issue_label (one row per issue + label). */
    @ElementCollection
    @CollectionTable(
            name = "issue_label",
            joinColumns = @JoinColumn(name = "issue_id"),
            indexes = @Index(name = "idx_issue_label_name", columnList = "label_name"))
    @OnDelete(action = OnDeleteAction.CASCADE)
    @Column(name = "label_name", nullable = false, length = 100)
    private Set<String> labels = new HashSet<>();

    /**
     * Copies the newer data from {@code newer} onto this row (used when a backfill sees an issue again).
     * Not copied: id (ours), source and externalId (they are what matched the two).
     * duplicateOf is only copied when {@code newer} has one: the tracker's JSON never contains it,
     * so copying null would erase an answer key that an earlier step filled in.
     */
    public void updateFrom(Issue newer) {
        this.repo = newer.repo;
        this.number = newer.number;
        this.title = newer.title;
        this.body = newer.body;
        this.state = newer.state;
        this.stateReason = newer.stateReason;
        this.issueType = newer.issueType;
        this.authorAssociation = newer.authorAssociation;
        this.milestone = newer.milestone;
        this.htmlUrl = newer.htmlUrl;
        this.createdAt = newer.createdAt;
        this.updatedAt = newer.updatedAt;
        this.closedAt = newer.closedAt;
        this.raw = newer.raw;
        if (newer.duplicateOf != null) {
            this.duplicateOf = newer.duplicateOf;
        }
        // Change the contents of the set, not the set itself: Hibernate tracks this exact
        // Set object to work out which issue_label rows to delete and insert.
        this.labels.clear();
        this.labels.addAll(newer.labels);
    }
}
