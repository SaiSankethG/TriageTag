package com.saisanketh.triage.github;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpMethod;
import org.springframework.http.MediaType;
import org.springframework.test.web.client.MockRestServiceServer;
import org.springframework.web.client.RestClient;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyPair;
import java.security.Signature;
import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.time.ZoneId;
import java.time.ZoneOffset;
import java.util.Base64;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.springframework.test.web.client.match.MockRestRequestMatchers.header;
import static org.springframework.test.web.client.match.MockRestRequestMatchers.method;
import static org.springframework.test.web.client.match.MockRestRequestMatchers.requestTo;
import static org.springframework.test.web.client.response.MockRestResponseCreators.withSuccess;

/** Uses a key generated by the test (GitHub's PKCS#1 format), a mock GitHub and a clock the test moves. */
class GitHubAppAuthTest {

    private static final Instant T0 = Instant.parse("2026-11-04T10:00:00Z");

    /** A clock the test can move forward. */
    static class MovableClock extends Clock {
        Instant now = T0;

        @Override
        public ZoneId getZone() {
            return ZoneOffset.UTC;
        }

        @Override
        public Clock withZone(ZoneId zone) {
            return this;
        }

        @Override
        public Instant instant() {
            return now;
        }
    }

    @TempDir
    Path dir;
    private KeyPair key;
    private Path keyFile;
    private final MovableClock clock = new MovableClock();
    private final RestClient.Builder builder = RestClient.builder();
    private final MockRestServiceServer server = MockRestServiceServer.bindTo(builder).build();
    private final JsonMapper json = JsonMapper.builder().build();

    @BeforeEach
    void writeTestKey() throws Exception {
        key = PemKeysTest.testKey();
        keyFile = dir.resolve("app.private-key.pem");
        Files.writeString(keyFile, PemKeysTest.pem("RSA PRIVATE KEY", PemKeysTest.pkcs1Of(key)));
    }

    private GitHubAppAuth auth() {
        return new GitHubAppAuth(builder, "https://api.github.com", "123456", keyFile.toString(), clock);
    }

    @Test
    void theAppJwtHasGitHubsClaimsAndAValidRs256Signature() throws Exception {
        String jwt = auth().appJwt();

        String[] parts = jwt.split("\\.");
        assertThat(parts).hasSize(3);
        JsonNode header = json.readTree(Base64.getUrlDecoder().decode(parts[0]));
        JsonNode payload = json.readTree(Base64.getUrlDecoder().decode(parts[1]));
        assertThat(header.get("alg").asString()).isEqualTo("RS256");
        assertThat(payload.get("iss").asString()).isEqualTo("123456");
        assertThat(payload.get("iat").asLong()).isEqualTo(T0.getEpochSecond() - 60);
        assertThat(payload.get("exp").asLong()).isEqualTo(T0.getEpochSecond() + 9 * 60);

        Signature rsa = Signature.getInstance("SHA256withRSA");
        rsa.initVerify(key.getPublic());
        rsa.update((parts[0] + "." + parts[1]).getBytes(StandardCharsets.US_ASCII));
        assertThat(rsa.verify(Base64.getUrlDecoder().decode(parts[2]))).isTrue();
    }

    @Test
    void theInstallationTokenIsCachedUntilFiveMinutesBeforeItExpires() {
        server.expect(requestTo("https://api.github.com/repos/octo-org/hello/installation"))
                .andExpect(method(HttpMethod.GET))
                .andExpect(header(HttpHeaders.AUTHORIZATION, org.hamcrest.Matchers.startsWith("Bearer eyJ")))
                .andRespond(withSuccess("{\"id\": 42}", MediaType.APPLICATION_JSON));
        server.expect(requestTo("https://api.github.com/app/installations/42/access_tokens"))
                .andExpect(method(HttpMethod.POST))
                .andRespond(withSuccess("{\"token\": \"ghs_first\", \"expires_at\": \"2026-11-04T11:00:00Z\"}",
                        MediaType.APPLICATION_JSON));
        server.expect(requestTo("https://api.github.com/app/installations/42/access_tokens"))
                .andExpect(method(HttpMethod.POST))
                .andRespond(withSuccess("{\"token\": \"ghs_second\", \"expires_at\": \"2026-11-04T12:00:00Z\"}",
                        MediaType.APPLICATION_JSON));
        GitHubAppAuth auth = auth();

        assertThat(auth.installationToken("octo-org/hello")).isEqualTo("ghs_first");
        clock.now = T0.plus(Duration.ofMinutes(54));                  // 6 min left: still cached, no request
        assertThat(auth.installationToken("octo-org/hello")).isEqualTo("ghs_first");
        clock.now = T0.plus(Duration.ofMinutes(56));                  // 4 min left: refresh (installation id is cached)
        assertThat(auth.installationToken("octo-org/hello")).isEqualTo("ghs_second");
        server.verify();
    }

    @Test
    void withoutAnAppIdOrKeyFileItIsNotConfigured() {
        GitHubAppAuth noId = new GitHubAppAuth(builder, "https://api.github.com", "", keyFile.toString(), clock);
        GitHubAppAuth noKey = new GitHubAppAuth(builder, "https://api.github.com", "123456", "", clock);
        GitHubAppAuth missingFile = new GitHubAppAuth(builder, "https://api.github.com", "123456",
                dir.resolve("nope.pem").toString(), clock);

        assertThat(auth().isConfigured()).isTrue();
        assertThat(noId.isConfigured()).isFalse();
        assertThat(noKey.isConfigured()).isFalse();
        assertThat(missingFile.isConfigured()).isFalse();
        assertThatThrownBy(noKey::appJwt).hasMessageContaining("GITHUB_APP_PRIVATE_KEY_PATH");
    }
}
