package com.saisanketh.triage.db;

import com.saisanketh.triage.comment.CommentService;
import com.saisanketh.triage.comment.CommentService.Decision;
import com.saisanketh.triage.comment.GitHubCommentClient.PostedComment;
import com.saisanketh.triage.domain.Issue;
import com.saisanketh.triage.embedding.IssueEmbeddingRepository;
import com.saisanketh.triage.report.TriageReport;
import com.saisanketh.triage.report.TriageService;
import com.saisanketh.triage.repository.IssueRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;

import java.time.Instant;
import java.util.List;

import static com.saisanketh.triage.service.TestIssues.issue;
import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.anyInt;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.contains;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.times;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

/**
 * Comment mode on real Postgres with the fake LLM and a mocked GitHub. The fake LLM says "yes" when the titles share at least
 * half their words, so "Datasource url not picked up" vs "... from yaml" is confirmed and "Banner colours" is not.
 */
class CommentServiceDbTest extends PostgresTest {

    private static final String REPO = "octo-org/hello";

    @Autowired
    private IssueRepository issueRepository;
    @Autowired
    private IssueEmbeddingRepository embeddingRepository;
    @Autowired
    private TriageService triageService;
    @Autowired
    private CommentService commentService;
    @Autowired
    private JdbcTemplate jdbc;
    @Autowired
    private io.micrometer.core.instrument.MeterRegistry registry;

    private static float[] direction(double angleDegrees) {
        float[] v = new float[384];
        v[0] = (float) Math.cos(Math.toRadians(angleDegrees));
        v[1] = (float) Math.sin(Math.toRadians(angleDegrees));
        return v;
    }

    private long save(int number, String createdAt, double angle, String title, String association, String... labels) {
        Issue issue = issue(number, title, labels);
        issue.setCreatedAt(Instant.parse(createdAt));
        issue.setAuthorAssociation(association);
        long id = issueRepository.saveAndFlush(issue).getId();
        embeddingRepository.saveAll(List.of(id), List.of(direction(angle)), "test");
        return id;
    }

    @BeforeEach
    void anOriginalAndAGitHubAppThatWorks() {
        save(1, "2024-01-01T00:00:00Z", 0, "Datasource url not picked up", "NONE");
        when(appAuth.isConfigured()).thenReturn(true);
        when(appAuth.installationToken(REPO)).thenReturn("ghs_test");
        when(commentClient.post(eq(REPO), anyInt(), anyString(), eq("ghs_test")))
                .thenReturn(new PostedComment(99, "https://github.com/octo-org/hello/issues/2#issuecomment-99"));
    }

    private void suggestMode() {
        jdbc.update("INSERT INTO repo_setting (repo, mode) VALUES ('octo-org/hello', 'SUGGEST')");
    }

    @Test
    void shadowModeIsTheDefaultAndNeverComments() {
        long id = save(2, "2024-06-01T00:00:00Z", 1, "Datasource url not picked up from yaml", "NONE");

        triageService.createIfMissing(id);

        verify(commentClient, never()).post(anyString(), anyInt(), anyString(), anyString());
        // Metrics: the new report's top match (#1, ~1.0) is "high", and comment mode decided SHADOW_MODE.
        assertThat(registry.get("triage.duplicates.suggested").tag("level", "high").counter().count()).isGreaterThanOrEqualTo(1);
        assertThat(registry.get("triage.comments").tag("decision", "SHADOW_MODE").counter().count()).isGreaterThanOrEqualTo(1);
    }

    @Test
    void inSuggestModeAConfirmedHighMatchGetsExactlyOneComment() {
        suggestMode();
        long id = save(2, "2024-06-01T00:00:00Z", 1, "Datasource url not picked up from yaml", "NONE");

        assertThat(triageService.createIfMissing(id)).isTrue();          // creates the report and posts
        TriageReport again = triageService.create(id);                  // e.g. regenerated by hand
        assertThat(commentService.maybeComment(again)).isEqualTo(Decision.ALREADY_HANDLED);

        verify(commentClient, times(1)).post(eq(REPO), eq(2), contains("#1 (Datasource url not picked up)"), eq("ghs_test"));
        assertThat(jdbc.queryForMap("SELECT status, comment_id FROM posted_comment WHERE issue_id = ?", id))
                .containsEntry("status", "POSTED").containsEntry("comment_id", 99L);
    }

    @Test
    void eachSafetyCheckStopsTheComment() {
        suggestMode();
        long team = save(2, "2024-06-01T00:00:00Z", 1, "Datasource url not picked up from yaml", "MEMBER");
        long clone = save(3, "2024-06-02T00:00:00Z", 1, "Datasource url not picked up from yaml", "NONE",
                "status: forward-port");
        long weak = save(4, "2024-06-03T00:00:00Z", 40, "Datasource url not picked up again", "NONE");
        long unconfirmed = save(5, "2024-06-04T00:00:00Z", 1, "Banner colours", "NONE");

        assertThat(commentService.maybeComment(triageService.create(team))).isEqualTo(Decision.TEAM_AUTHOR);
        assertThat(commentService.maybeComment(triageService.create(clone))).isEqualTo(Decision.SKIP_LABEL);
        assertThat(commentService.maybeComment(triageService.create(weak))).isEqualTo(Decision.BELOW_THRESHOLD);
        assertThat(commentService.maybeComment(triageService.create(unconfirmed))).isEqualTo(Decision.NOT_CONFIRMED);
        when(appAuth.isConfigured()).thenReturn(false);
        assertThat(commentService.maybeComment(triageService.create(team))).isEqualTo(Decision.NOT_CONFIGURED);
        verify(commentClient, never()).post(anyString(), anyInt(), anyString(), anyString());
    }

    @Test
    void aFailedPostIsRecordedAndNotRetried() {
        suggestMode();
        long id = save(2, "2024-06-01T00:00:00Z", 1, "Datasource url not picked up from yaml", "NONE");
        when(commentClient.post(eq(REPO), eq(2), anyString(), anyString())).thenThrow(new IllegalStateException("502"));
        TriageReport report = triageService.create(id);

        assertThat(commentService.maybeComment(report)).isEqualTo(Decision.FAILED);
        assertThat(commentService.maybeComment(report)).isEqualTo(Decision.ALREADY_HANDLED);
        assertThat(jdbc.queryForObject("SELECT error FROM posted_comment WHERE issue_id = ?", String.class, id))
                .contains("502");
    }
}
